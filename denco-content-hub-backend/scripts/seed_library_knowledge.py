def _make_tiptap_doc(text: str) -> dict:
    """Конвертирует plain text в TipTap JSON документ."""
    paragraphs = []
    for line in text.strip().split("\n"):
        line = line.strip()
        if line:
            paragraphs.append({"type": "paragraph", "content": [{"type": "text", "text": line}]})
        else:
            paragraphs.append({"type": "paragraph", "content": []})
    return {"type": "doc", "content": paragraphs}


async def _get_company_id(session, args_company_id: int | None) -> int:
    """Получить company_id: из аргумента или первую компанию в БД."""
    if args_company_id:
        result = await session.execute(
            select(Company).where(
                Company.id == args_company_id,
                Company.deleted_at.is_(None),
            )
        )
        company = result.scalar_one_or_none()
        if not company:
            logger.error("Компания не найдена", company_id=args_company_id)
            sys.exit(1)
        return company.id

    # Ищем дефолтную или первую компанию
    result = await session.execute(
        select(Company)
        .where(Company.deleted_at.is_(None))
        .order_by(Company.is_default.desc(), Company.id.asc())
        .limit(1)
    )
    company = result.scalar_one_or_none()
    if not company:
        logger.error("В БД нет ни одной компании")
        sys.exit(1)
    logger.info("Используем компанию", company_id=company.id, name=company.name)
    return company.id


async def _get_user_id(session, company_id: int, args_user_id: int | None) -> int:
    """Получить user_id: из аргумента или первый участник компании."""
    if args_user_id:
        return args_user_id

    result = await session.execute(
        select(CompanyMember.user_id)
        .where(CompanyMember.company_id == company_id)
        .order_by(CompanyMember.id.asc())
        .limit(1)
    )
    user_id = result.scalar_one_or_none()
    if not user_id:
        logger.error("В компании нет участников", company_id=company_id)
        sys.exit(1)
    logger.info("Используем пользователя", user_id=user_id)
    return user_id


async def _find_node_by_title(
    session,
    title: str,
    company_id: int,
) -> int | None:
    """Найти узел по title в рамках компании."""
    result = await session.execute(
        select(KnowledgeNode.id).where(
            KnowledgeNode.title == title,
            KnowledgeNode.company_id == company_id,
            KnowledgeNode.deleted_at.is_(None),
        )
    )
    return result.scalar_one_or_none()


async def _seed_edges(
    session,
    company_id: int,
    user_id: int,
) -> tuple[int, int]:
    """Создать связи между узлами. Возвращает (created, skipped)."""
    created = 0
    skipped = 0

    for edge_data in SEED_EDGES:
        source_id = await _find_node_by_title(session, edge_data["source"], company_id)
        target_id = await _find_node_by_title(session, edge_data["target"], company_id)

        if source_id is None:
            logger.warning("Узел-источник не найден", title=edge_data["source"])
            skipped += 1
            continue
        if target_id is None:
            logger.warning("Узел-цель не найден", title=edge_data["target"])
            skipped += 1
            continue

        # Проверка на дубликат
        result = await session.execute(
            select(KnowledgeEdge.id).where(
                KnowledgeEdge.source_node_id == source_id,
                KnowledgeEdge.target_node_id == target_id,
                KnowledgeEdge.label == edge_data["label"],
                KnowledgeEdge.deleted_at.is_(None),
            )
        )
        if result.scalar_one_or_none() is not None:
            logger.info(
                "Пропуск связи (уже существует)",
                source=edge_data["source"],
                target=edge_data["target"],
                label=edge_data["label"],
            )
            skipped += 1
            continue

        edge = KnowledgeEdge(
            source_node_id=source_id,
            target_node_id=target_id,
            label=edge_data["label"],
            weight=1.0,
            created_by_user_id=user_id,
        )
        session.add(edge)
        logger.info(
            "Создана связь",
            source=edge_data["source"],
            target=edge_data["target"],
            label=edge_data["label"],
        )
        created += 1

    return created, skipped


async def seed() -> None:
    parser = argparse.ArgumentParser(description="Seed Library Knowledge Graph")
    parser.add_argument("--company-id", type=int, default=None)
    parser.add_argument("--user-id", type=int, default=None)
    args = parser.parse_args()

    nodes_created = 0
    nodes_skipped = 0

    async with async_session_factory() as session:
        company_id = await _get_company_id(session, args.company_id)
        user_id = await _get_user_id(session, company_id, args.user_id)

        for node_data in SEED_NODES:
            node_type = node_data["node_type"]
            title = node_data["title"]

            # Проверка на дубликат
            result = await session.execute(
                select(KnowledgeNode.id).where(
                    KnowledgeNode.node_type == node_type,
                    KnowledgeNode.title == title,
                    KnowledgeNode.company_id == company_id,
                    KnowledgeNode.deleted_at.is_(None),
                )
            )
            if result.scalar_one_or_none() is not None:
                logger.info("Пропуск (уже существует)", type=node_type, title=title)
                nodes_skipped += 1
                continue

            content_text = node_data["content_text"]
            content = _make_tiptap_doc(content_text)

            node = KnowledgeNode(
                node_type=node_type,
                title=title,
                content=content,
                content_text=content_text,
                scope_type=ScopeType.COMPANY,
                company_id=company_id,
                workspace_id=None,
                created_by_user_id=user_id,
                updated_by_user_id=user_id,
            )
            session.add(node)
            logger.info("Создан узел", type=node_type, title=title)
            nodes_created += 1

        await session.flush()

        # Создаём связи
        edges_created, edges_skipped = await _seed_edges(session, company_id, user_id)

        await session.commit()

    logger.info(
        "Seed завершён",
        nodes_created=nodes_created,
        nodes_skipped=nodes_skipped,
        nodes_total=len(SEED_NODES),
        edges_created=edges_created,
        edges_skipped=edges_skipped,
        edges_total=len(SEED_EDGES),
    )


